import { chromium } from "playwright";
import fs from "fs";
import path from "path";
const env = Object.fromEntries(fs.readFileSync(".env","utf8").split("\n").filter(l=>l.includes("=")).map(l=>{ const i=l.indexOf("="); return [l.slice(0,i).trim(), l.slice(i+1).trim()]}));
const USER = env.PORTAL_USER; const PASS = env.PORTAL_PASS; const CNPJ = env.PORTAL_CNPJ;
const BASE = "https://operacao.portaldecompraspublicas.com.br";
console.log(`Mapeando portal user=${USER} cnpj=${CNPJ}`);
const browser = await chromium.launch({ headless: false, args: ["--disable-blink-features=AutomationControlled"] });
const ctx = await browser.newContext({ viewport: { width:1280, height:800 }});
const page = await ctx.newPage();
const logs=[];
page.on("request", r=>{ const u=r.url(); if(u.includes("/api")||u.includes("lance")||u.includes("lote")||u.includes("processo")||u.includes("ws")||u.includes("socket")) logs.push(`REQ ${r.method()} ${u}`); });
page.on("response", async r=>{ const u=r.url(); if(u.includes("/api")||u.includes("lance")||u.includes("lote")||u.includes("processo")){ try{ const t=await r.text(); logs.push(`RES ${r.status()} ${u.slice(0,300)} => ${t.slice(0,1200)}`);}catch{}} });
page.on("websocket", ws=>{ logs.push(`WS OPEN ${ws.url()}`); ws.on("framereceived", ({payload})=>{ const s=payload instanceof Buffer?payload.toString():String(payload); logs.push(`WS FRAME ${ws.url().slice(0,120)} <= ${s.slice(0,800)}`); }); ws.on("framesent", ({payload})=>{ const s=payload instanceof Buffer?payload.toString():String(payload); logs.push(`WS SEND ${ws.url().slice(0,120)} => ${s.slice(0,800)}`); }); });
console.log("GOTO /18/loginext/");
await page.goto(`${BASE}/18/loginext/`, { waitUntil:"domcontentloaded", timeout:60000 });
await page.waitForTimeout(1500);
console.log("URL after goto", page.url());
await page.fill("#username", USER);
await page.fill("#password", PASS);
await page.click("#kc-login");
console.log("clicked login, waiting...");
try{ await page.waitForURL(url=> url.href.includes("operacao.portaldecompraspublicas.com.br") && !url.href.includes("/realms/"), { timeout:30000 }); }catch(e){ console.log("waitForURL timeout", e.message); }
await page.waitForTimeout(3000);
console.log("URL after login", page.url());
console.log("TITLE", await page.title());
const ls = await page.evaluate(()=> JSON.stringify({ local: Object.fromEntries(Object.entries(localStorage).slice(0,50).map(([k,v])=>[k, String(v).slice(0,800)])), session: Object.fromEntries(Object.entries(sessionStorage).slice(0,50).map(([k,v])=>[k, String(v).slice(0,800)])), cookies: document.cookie.slice(0,2000) }, null, 2));
fs.writeFileSync("map-ls.json", ls); console.log(ls.slice(0,4000));
if(page.url().includes("/realms/")){ const err = await page.locator(".pf-c-alert, .alert-error, #input-error, [role=alert]").allTextContents().catch(()=>[]); console.log("LOGIN ERROR", err, await page.content().then(s=>s.slice(0,3000))); }
await ctx.storageState({ path: `storage/${CNPJ}.json` }); console.log("saved storage");
await page.waitForTimeout(2000);
console.log("TRY navigate to processos");
await page.goto(`${BASE}/`, { waitUntil:"domcontentloaded" }).catch(()=>{});
await page.waitForTimeout(4000);
console.log("URL now", page.url());
const html = await page.content(); fs.writeFileSync("map-page.html", html); console.log("dumped map-page.html", html.slice(0,3000));
fs.writeFileSync("map-log.txt", logs.join("\n")); console.log("logs", logs.slice(0,80).join("\n").slice(0,5000));
await page.waitForTimeout(120000);
await browser.close();
